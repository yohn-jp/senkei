import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "vite";
import { expect, test } from "@playwright/test";
import { campaignCore } from "../helpers/campaign-core";
import { nativeCampaignFixture, nativeCampaignStore } from "../helpers/native-campaign-fixture";
import { completePreflight } from "../helpers/preflight";
test.use({ actionTimeout: 20_000 });

test("Genuine native Campaign Experiment preserves exact IDs and wins an unchanged frozen rematch in WASM", async ({ page }) => {
  test.setTimeout(600_000);
  const fixture = await nativeCampaignFixture();
  const core = await campaignCore();
  const ownCompile = core("compile_text", { ruleset_ref: fixture.rules.ruleset, source: fixture.source });
  const npcCompile = core("compile_text", { ruleset_ref: fixture.rules.ruleset, source: fixture.npcSource });
  expect(ownCompile.program.content_digest).toBe(fixture.snapshot.attacker.program.content_digest);
  expect(npcCompile.program.content_digest).toBe(fixture.snapshot.defender.program.content_digest);
  const store = nativeCampaignStore(fixture, ownCompile.estimated_cu);
  const setup = store.experiments[0].setup;
  const definition = fixture.snapshot.attacker;
  const server = await createServer({ configFile: false, root: process.cwd(), logLevel: "silent", server: { middlewareMode: true }, appType: "custom" });
  try {
    const { parseSavedNextSetup } = await server.ssrLoadModule("/apps/web/src/features/next/NextWorkspace.tsx");
    expect(parseSavedNextSetup(setup)).toEqual(setup);
  } finally { await server.close(); }
  mkdirSync("test-results", { recursive: true });
  const path = "test-results/campaign-genuine-native-experiment.json";
  writeFileSync(path, JSON.stringify(store));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  const readProgress = () => page.evaluate(digest => JSON.parse(localStorage.getItem(`senkei.next-campaign-progress.v2:${digest}`)!), definition.ruleset.digest);
  await expect.poll(readProgress).not.toBeNull();
  const editableSource = await page.evaluate(() => JSON.parse(localStorage.getItem("senkei.next-workspace-recovery.v1")!).draft.program_input.source);
  await page.evaluate(({ digest, legacy }) => { localStorage.removeItem(`senkei.next-campaign-progress.v2:${digest}`); localStorage.setItem(`senkei.next-campaign-progress.v1:${digest}`, legacy); }, { digest: definition.ruleset.digest, legacy: fixture.legacy });
  await page.reload();
  await page.getByTestId("nav-library").click();
  const library = page.getByTestId("next-library");
  await library.getByLabel("Import Next experiment file").setInputFiles(path);
  await expect(library.getByRole("button", { name: "Open latest comparison", exact: true })).toBeEnabled({ timeout: 60_000 });
  await library.getByRole("button", { name: "Open latest comparison", exact: true }).click();
  await expect(page.getByTestId("battle-analysis")).toBeVisible();
  expect((await readProgress()).completed_scenario_ids).toEqual([]); // Viewing an actual old win must not award progress.
  await page.getByRole("button", { name: /同条件で再戦 · Run Snapshot/ }).click();
  await expect(page.getByTestId("journey-ready")).toContainText("Regroup for a base defense");
  await completePreflight(page);
  const confirmed = page.getByText(/Confirmed result · (Attacker Victory|Defender Victory|Draw)/i);
  await expect(confirmed).toBeVisible({ timeout: 300_000 });
  await page.getByTestId("nav-library").click();
  await expect(library.locator(".next-library-experiment-list li")).toHaveCount(2, { timeout: 60_000 });
  const downloadEvent = page.waitForEvent("download");
  await library.getByRole("button", { name: "Export experiments", exact: true }).click();
  const exported = await downloadEvent;
  await exported.saveAs("test-results/campaign-exact-rematch-records.json");
  const persisted = JSON.parse(readFileSync("test-results/campaign-exact-rematch-records.json", "utf8"));
  expect(persisted.experiments[0].snapshot).toEqual(fixture.snapshot);
  expect(persisted.experiments[0].response.outcome.result).toEqual(fixture.actual.result);
  await library.getByRole("button", { name: "Back", exact: true }).click();
  await expect(confirmed).toContainText("Attacker Victory");
  await expect.poll(readProgress).toMatchObject({ completed_scenario_ids: [fixture.scenario.id], history_incomplete: true });
  expect(await page.evaluate(digest => localStorage.getItem(`senkei.next-campaign-progress.v1:${digest}`), definition.ruleset.digest)).toBe(fixture.legacy);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".next-battle-panel.has-campaign-result")).toHaveCSS("overflow-y", "auto");
  const actions = page.getByRole("region", { name: "Campaign next actions" });
  await expect(actions).toContainText("最終課題を攻略");
  await expect(actions).toContainText("全課題攻略済みとは表示しません");
  await expect(actions.getByRole("button", { name: /次の課題を準備/ })).toHaveCount(0);
  await actions.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/campaign-live-final-victory-390.png", fullPage: true });
  await actions.getByRole("button", { name: "結果を分析", exact: true }).click();
  await actions.getByRole("button", { name: "Replayで結果を見る", exact: true }).click();
  await actions.getByRole("button", { name: "この課題のJinreiを改善", exact: true }).click();
  await page.getByRole("tab", { name: "Jinrei Text", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Jinrei source", exact: true })).toHaveValue(editableSource);
  await page.locator("#next-tab-battle").click();
  await actions.getByRole("button", { name: "Homeへ戻る", exact: true }).click();
  await page.getByTestId("journey-home").locator(".journey-start-mobile details > summary").click();
  await page.getByRole("button", { name: "戦役を始める", exact: true }).click();
  await expect(page.getByRole("region", { name: "Campaign completion records" })).toContainText("最終課題：攻略記録あり");
  await expect(page.getByRole("button", { name: /March to the lane/ })).toContainText("攻略履歴不明");
});
