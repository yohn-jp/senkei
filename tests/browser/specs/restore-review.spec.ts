import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";

for (const width of [320, 390, 1440]) test(`UX-C09 review cancel export and restore at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.goto("/");
  const home = page.getByTestId("journey-home");
  await expect(home).toBeVisible({ timeout: 60_000 });
  if (width < 761) await home.getByText("戦役・自由編成・再開", { exact: true }).click();
  await home.getByRole("button", { name: "戦役を始める", exact: true }).click();
  await page.getByRole("button", { name: "この課題で準備する" }).click();
  await page.getByRole("button", { name: "準備確認へ", exact: true }).click();
  await page.getByTestId("nav-library").click();
  const library = page.getByTestId("next-library");
  await library.getByRole("button", { name: "Save current setup", exact: true }).click();
  const pinned = await page.evaluate(() => localStorage.getItem("senkei.next-workspace.v1"));
  expect(JSON.parse(pinned!).campaign_scenario_id).toBeTruthy();
  await library.getByRole("button", { name: "Back", exact: true }).click();
  await page.getByTestId("journey-ready").getByRole("button", { name: "Homeへ戻る" }).click();
  await home.getByRole("button", { name: "すぐ戦う", exact: true }).click();
  await page.getByTestId("nav-library").click();
  const originalCurrent = await page.evaluate(() => localStorage.getItem("senkei.next-workspace-recovery.v1"));
  const restoreButton = library.getByRole("button", { name: "Restore pinned setup", exact: true });
  await restoreButton.click();
  const review = library.getByRole("alertdialog", { name: "Replace the current Draft with the pinned setup?" });
  await expect(review).toBeVisible();
  await expect(review).toContainText("Scenario:");
  await expect(review).toContainText("Starter");
  await review.getByRole("button", { name: "Keep current Draft", exact: true }).click();
  await expect(review).toHaveCount(0);
  await expect(restoreButton).toBeFocused();
  expect(await page.evaluate(() => localStorage.getItem("senkei.next-workspace-recovery.v1"))).toBe(originalCurrent);
  expect(await page.evaluate(() => localStorage.getItem("senkei.next-workspace.v1"))).toBe(pinned);
  await library.getByRole("button", { name: "Restore pinned setup", exact: true }).click();
  const downloadEvent = page.waitForEvent("download");
  await review.getByRole("button", { name: "Export current Draft first", exact: true }).click();
  const download = await downloadEvent;
  const exported = JSON.parse(readFileSync((await download.path())!, "utf8"));
  expect(exported.campaign_scenario_id ?? null).toBeNull();
  expect(exported.draft).toEqual(JSON.parse(pinned!).draft);
  await expect(review).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem("senkei.next-workspace.v1"))).toBe(pinned);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  for (const name of ["Keep current Draft", "Export current Draft first", "Replace current Draft"]) {
    const button = review.getByRole("button", { name, exact: true });
    await button.scrollIntoViewIfNeeded();
    const bounds = await button.boundingBox();
    expect(bounds!.y).toBeGreaterThanOrEqual(0);
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(900);
  }
  await page.screenshot({ path: `test-results/restore-review-${width}.png`, fullPage: true });
  await review.getByRole("button", { name: "Replace current Draft", exact: true }).click();
  await expect(page.getByTestId("journey-ready").locator(".journey-ready-challenge")).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem("senkei.next-workspace.v1"))).toBe(pinned);
  await page.getByTestId("nav-library").click();
  await library.getByRole("button", { name: "Restore pinned setup", exact: true }).click();
  await expect(page.getByTestId("journey-ready")).toBeVisible();
  await expect(page.getByRole("alertdialog")).toHaveCount(0);
});
