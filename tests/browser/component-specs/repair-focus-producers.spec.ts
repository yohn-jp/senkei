import { resolve } from "node:path";
import { expect, test } from "@playwright/test";
for (const width of [390, 1440]) test(`real Core targets focus component fields without editing at ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 900 });
  const entry = "/@fs" + resolve(import.meta.dirname, "../fixtures/repair-focus-harness.tsx");
  await page.route("**/repair-focus-harness", route => route.fulfill({ contentType: "text/html", body: `<div id="root"></div><script type="module">import R from '/@react-refresh'; R.injectIntoGlobalHook(window); window.$RefreshReg$=()=>{}; window.$RefreshSig$=()=>t=>t; window.__vite_plugin_react_preamble_installed__=true; await import(${JSON.stringify(entry)});</script>` }));
  await page.goto("/repair-focus-harness");
  await expect(page.getByRole("button", { name: "Repair skill_path", exact: true })).toBeVisible({ timeout: 30_000 });
  await page.getByRole("button", { name: /Inspect .* without adopting/ }).last().click();
  await expect(page.getByRole("region", { name: "Candidate adoption preview" })).toBeVisible();
  await page.getByRole("button", { name: "Repair skill_path", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Skill Tree" })).toHaveAttribute("aria-selected", "true");
  await expect(page.locator(".ha-branches button:enabled").first()).toBeFocused();
  await expect(page.getByRole("region", { name: "Candidate adoption preview" })).toHaveCount(0);
  await page.getByRole("button", { name: "Repair node", exact: true }).click();
  await expect(page.getByRole("combobox", { name: /Starting node for Squad/ }).nth(2)).toBeFocused();
  if (width < 761) await expect(page.getByRole("button", { name: "3 · Start nodes", exact: true })).toHaveAttribute("aria-current", "step");
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  await page.screenshot({ path: testInfo.outputPath(`node-${width}.png`), fullPage: true });
  await page.getByRole("button", { name: "Repair squad", exact: true }).click();
  await expect(page.locator(".ha-member select").nth(2)).toBeFocused();
  if (width < 761) await expect(page.getByRole("button", { name: "2 · Assign", exact: true })).toHaveAttribute("aria-current", "step");
  await page.getByRole("tab", { name: "Hero Collection" }).click();
  await page.getByRole("button", { name: "Hide workspace", exact: true }).click();
  await page.getByRole("button", { name: "Show workspace", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Hero Collection" })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Repair catalog_id", exact: true }).click();
  await expect(page.getByRole("button", { name: "Choose hero for slot 3", exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Repair BOM skill", exact: true }).click();
  await expect.poll(async () => JSON.parse(await page.getByTestId("hero-request").innerText()).target.slotId).toBe("\uFEFF");
  await expect(page.locator(".ha-branches button:enabled").first()).toBeFocused();
  await page.getByRole("button", { name: "Repair squad", exact: true }).click();
  await expect(page.locator(".ha-member select").nth(2)).toBeFocused();
  await page.getByRole("button", { name: "Unknown slot request", exact: true }).click();
  await expect(page.getByRole("status", { name: "Hero repair focus" })).toContainText("unavailable");
  await page.getByRole("button", { name: "Hide workspace", exact: true }).click();
  const priorRequest = await page.getByTestId("hero-request").innerText();
  await page.getByRole("button", { name: "Repair skill_path", exact: true }).click();
  await expect(page.getByTestId("hero-request")).not.toHaveText(priorRequest);
  await expect(page.locator("#next-atelier-skills")).toHaveAttribute("aria-selected", "false");
  await page.getByRole("button", { name: "Show workspace", exact: true }).click();
  await expect(page.locator(".ha-branches button:enabled").first()).toBeFocused();
  await page.getByRole("button", { name: "Repair compiler", exact: true }).click();
  const editor = page.getByRole("textbox", { name: "Jinrei source", exact: true });
  await expect(editor).toBeFocused();
  const request = JSON.parse(await page.getByTestId("source-request").innerText());
  const state = await editor.evaluate((input: HTMLTextAreaElement) => ({ value: input.value, cursor: input.selectionStart }));
  const bytes = Number(request.target.path.slice("source@".length));
  expect(state.cursor).toBe(new TextDecoder().decode(new TextEncoder().encode(request.exactSource).slice(0, bytes)).replace(/\r\n?/g, "\n").length);
  await page.getByRole("button", { name: "Unavailable source request", exact: true }).click();
  await expect(page.getByRole("status", { name: "Jinrei repair focus" })).toContainText("unavailable");
  await expect(page.getByRole("status", { name: "Jinrei repair focus" })).toBeFocused();
  await page.getByRole("tab", { name: /Behavior Coverage/ }).click();
  await page.getByRole("button", { name: "Hide workspace", exact: true }).click();
  await page.getByRole("button", { name: "Show workspace", exact: true }).click();
  await expect(page.getByRole("tab", { name: /Behavior Coverage/ })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Stale source request", exact: true }).click();
  await expect(page.getByRole("status", { name: "Jinrei repair focus" })).toContainText("unavailable");
  await expect(page.getByRole("tab", { name: /Behavior Coverage/ })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Repair compiler", exact: true }).click();
  await expect(editor).toBeFocused();
  await expect(page.getByTestId("writes")).toHaveText("0");
  await page.screenshot({ path: testInfo.outputPath(`source-${width}.png`), fullPage: true });
});
